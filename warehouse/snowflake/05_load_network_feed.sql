CREATE TABLE IF NOT EXISTS REMITTANCE (
    remit_batch_id       VARCHAR,
    dealer_number        VARCHAR,
    contract_number      VARCHAR,
    remit_amount         VARCHAR,
    remit_date           VARCHAR,
