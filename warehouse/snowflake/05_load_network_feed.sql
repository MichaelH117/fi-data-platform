-- payload is VARIANT here and JSON text in DuckDB; staging reads it through a cross-database macro.
CREATE TABLE IF NOT EXISTS ECONTRACT_EVENTS (
    event_id             VARCHAR,
    contract_number      VARCHAR,
    event_type           VARCHAR,
    event_at             VARCHAR,
    payload              VARIANT,
    _source_file         VARCHAR,
    _file_sha256         VARCHAR,
    _row_number          NUMBER,
    _feed_date           DATE,
    _loaded_at           TIMESTAMP_LTZ,
    _loaded_by           VARCHAR       DEFAULT 'copy@LOADER',
    _source_system       VARCHAR       DEFAULT 'network_feed',
    _source_version      NUMBER,
    _is_deleted          BOOLEAN       DEFAULT FALSE,
    _run_id              VARCHAR
);

-- The manifest lands whole; the view below flattens it to one row per file.
CREATE TABLE IF NOT EXISTS _MANIFEST_RAW (
    manifest             VARIANT,
    _source_file         VARCHAR,
    _loaded_at           TIMESTAMP_LTZ
);

-- -----------------------------------------------------------------------------------------------------
-- COPY: one statement per file type. PATTERN picks the file across every dated folder.
-- -----------------------------------------------------------------------------------------------------
COPY INTO DEALS
    FROM @LANDING
    PATTERN = '.*/deals[.]csv'
    FILE_FORMAT = (FORMAT_NAME = 'FF_CSV_HEADER')
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (_source_file = METADATA$FILENAME, _row_number = METADATA$FILE_ROW_NUMBER,
                        _file_sha256 = METADATA$FILE_CONTENT_KEY, _loaded_at = METADATA$START_SCAN_TIME)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO REMITTANCE
    FROM @LANDING
    PATTERN = '.*/remittance[.]csv'
    FILE_FORMAT = (FORMAT_NAME = 'FF_CSV_HEADER')
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (_source_file = METADATA$FILENAME, _row_number = METADATA$FILE_ROW_NUMBER,
                        _file_sha256 = METADATA$FILE_CONTENT_KEY, _loaded_at = METADATA$START_SCAN_TIME)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO ECONTRACT_EVENTS
    FROM @LANDING
    PATTERN = '.*/econtract_events[.]jsonl'
    FILE_FORMAT = (FORMAT_NAME = 'FF_JSONL')
    MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
    INCLUDE_METADATA = (_source_file = METADATA$FILENAME, _row_number = METADATA$FILE_ROW_NUMBER,
                        _file_sha256 = METADATA$FILE_CONTENT_KEY, _loaded_at = METADATA$START_SCAN_TIME)
    ON_ERROR = ABORT_STATEMENT;

COPY INTO _MANIFEST_RAW (manifest, _source_file, _loaded_at)
    FROM (SELECT $1, METADATA$FILENAME, METADATA$START_SCAN_TIME FROM @LANDING)
    PATTERN = '.*/_manifest[.]json'
    FILE_FORMAT = (TYPE = JSON STRIP_OUTER_ARRAY = FALSE);

-- Fill the feed date (folder name) and manifest sequence on the rows this load added.
UPDATE DEALS            SET _feed_date = TO_DATE(SPLIT_PART(_source_file, '/', 1)) WHERE _feed_date IS NULL;
UPDATE REMITTANCE       SET _feed_date = TO_DATE(SPLIT_PART(_source_file, '/', 1)) WHERE _feed_date IS NULL;
UPDATE ECONTRACT_EVENTS SET _feed_date = TO_DATE(SPLIT_PART(_source_file, '/', 1)) WHERE _feed_date IS NULL;

CREATE OR REPLACE VIEW _MANIFEST AS
SELECT
    m.manifest:feed_date::DATE            AS feed_date,
    m.manifest:sequence_no::NUMBER        AS sequence_no,
    f.key::VARCHAR                        AS file_name,
    f.value:row_count::NUMBER             AS expected_rows,
    f.value:sha256::VARCHAR               AS expected_sha256,
    m.manifest:generated_at::TIMESTAMP_NTZ AS generated_at,
    m._loaded_at
FROM _MANIFEST_RAW AS m,
    LATERAL FLATTEN(input => m.manifest:files) AS f;

UPDATE DEALS AS d SET _source_version = v.sequence_no
FROM _MANIFEST AS v
WHERE d._source_version IS NULL AND v.feed_date = d._feed_date AND v.file_name = 'deals.csv';
UPDATE REMITTANCE AS r SET _source_version = v.sequence_no
FROM _MANIFEST AS v
WHERE r._source_version IS NULL AND v.feed_date = r._feed_date AND v.file_name = 'remittance.csv';
UPDATE ECONTRACT_EVENTS AS e SET _source_version = v.sequence_no
FROM _MANIFEST AS v
WHERE e._source_version IS NULL AND v.feed_date = e._feed_date AND v.file_name = 'econtract_events.jsonl';

