-- =====================================================================================================
-- 05  Load the dealer-integration network feed into RAW.NETWORK_FEED
-- Written for Snowflake, NOT executed by this repo. Locally the same job is `python -m ingest`.
--
-- Flow per business day (data/landing/YYYY-MM-DD/):
--   1. `python -m ingest.feed` checks the manifest (sha256 + row count) and the data contracts.
--   2. The loader uploads the folder to the internal stage, keeping the date as the path prefix:
--        PUT file://data/landing/2026-10-21/* @RAW.NETWORK_FEED.LANDING/2026-10-21/ AUTO_COMPRESS = FALSE;
--   3. COPY INTO lands every file untouched (all text), plus lineage columns.
-- COPY keeps 64 days of load history per table and skips files it has already loaded, so re-running
-- a day is a no-op (the same idempotency the local ingest gets from its watermark).
--
-- The Admin Core and legacy tables are not loaded here: a change-tracking CDC connector replicates
-- them into RAW.ADMIN_CORE / RAW.LEGACY_ADMIN with the same audit columns (_loaded_at, _source_version,
-- _is_deleted). Their DDL is generated by the connector from the source schema.
-- =====================================================================================================

USE ROLE LOADER;
USE WAREHOUSE LOADING;
USE SCHEMA RAW.NETWORK_FEED;

-- PARSE_HEADER lets COPY match CSV columns by name, so a new column in the feed never shifts data.
CREATE FILE FORMAT IF NOT EXISTS FF_CSV_HEADER
    TYPE = CSV
    PARSE_HEADER = TRUE
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    EMPTY_FIELD_AS_NULL = TRUE
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
    ENCODING = 'UTF8';

CREATE FILE FORMAT IF NOT EXISTS FF_JSONL
    TYPE = JSON
    STRIP_OUTER_ARRAY = FALSE;

CREATE STAGE IF NOT EXISTS LANDING
    DIRECTORY = (ENABLE = TRUE)
    COMMENT = 'Internal stage. One folder per feed date, same layout as data/landing/.';

-- Lineage + audit columns (docs/V3_DESIGN.md 2.6). Business columns stay VARCHAR: staging casts them.
