    contract_number      VARCHAR,
    vin                  VARCHAR,
    chassis_vin          VARCHAR,
    sale_date            VARCHAR,
    product_code         VARCHAR,
    plan_code            VARCHAR,
    term_months          VARCHAR,
    term_miles           VARCHAR,
    odometer             VARCHAR,
    vehicle_year         VARCHAR,
    vehicle_make         VARCHAR,
    vehicle_model        VARCHAR,
    fuel_type            VARCHAR,
    cylinders            VARCHAR,
    drive_type           VARCHAR,
    new_used             VARCHAR,
    is_commercial        VARCHAR,
    title_brand          VARCHAR,
    msrp                 VARCHAR,
    purchase_price       VARCHAR,
    coverage_cost        VARCHAR,
    retail_price         VARCHAR,
    surcharge_codes      VARCHAR,
    option_codes         VARCHAR,
    finance_type         VARCHAR,
    finance_amount       VARCHAR,
