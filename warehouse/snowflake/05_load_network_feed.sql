    _loaded_by           VARCHAR       DEFAULT 'copy@LOADER',
    _source_system       VARCHAR       DEFAULT 'network_feed',
    _source_version      NUMBER,
    _is_deleted          BOOLEAN       DEFAULT FALSE,
