-- =====================================================================================================
-- 03  Roles, service users and grants (least privilege)
-- Written for Snowflake, NOT executed by this repo.
--
--   Role         Warehouse      Can read                         Can write
--   LOADER       LOADING        RAW                              RAW (tables, stages, file formats)
--   TRANSFORMER  TRANSFORMING   RAW, ANALYTICS                   ANALYTICS (dbt owns what it builds)
--   REPORTER     REPORTING      ANALYTICS marts only             nothing
--
-- REPORTER cannot see RAW, STAGING or INTERMEDIATE: reports and BI read marts only, and rows are
-- filtered per user by the row access policies in 04. All three roles roll up to SYSADMIN so an
-- administrator can manage every object they create.
-- =====================================================================================================

-- Roles and users are created by USERADMIN; grants are made by SECURITYADMIN.
USE ROLE USERADMIN;

CREATE ROLE IF NOT EXISTS LOADER      COMMENT = 'Writes the raw landing zone.';
CREATE ROLE IF NOT EXISTS TRANSFORMER COMMENT = 'Runs dbt: reads RAW, builds ANALYTICS.';
CREATE ROLE IF NOT EXISTS REPORTER    COMMENT = 'Read-only on marts, filtered by row access policy.';

-- Service users authenticate with key pairs (no passwords). TYPE = SERVICE blocks interactive login.
-- Attach the public key after creating the key pair outside the repo:
--   ALTER USER SVC_LOADER SET RSA_PUBLIC_KEY = '<base64 public key>';
-- The private key stays in the orchestrator's secret store (dbt reads SNOWFLAKE_PRIVATE_KEY_PATH).
CREATE USER IF NOT EXISTS SVC_LOADER
    TYPE = SERVICE
    DEFAULT_ROLE = LOADER
    DEFAULT_WAREHOUSE = LOADING
    COMMENT = 'Ingest and network-feed loads.';

CREATE USER IF NOT EXISTS SVC_TRANSFORMER
    TYPE = SERVICE
    DEFAULT_ROLE = TRANSFORMER
    DEFAULT_WAREHOUSE = TRANSFORMING
    DEFAULT_NAMESPACE = ANALYTICS
    COMMENT = 'dbt (Airflow and CI).';

CREATE USER IF NOT EXISTS SVC_REPORTING
    TYPE = SERVICE
    DEFAULT_ROLE = REPORTER
    DEFAULT_WAREHOUSE = REPORTING
    DEFAULT_NAMESPACE = ANALYTICS
    COMMENT = 'Scheduled report site and dealer packet builds.';

USE ROLE SECURITYADMIN;

GRANT ROLE LOADER      TO ROLE SYSADMIN;
GRANT ROLE TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE REPORTER    TO ROLE SYSADMIN;

GRANT ROLE LOADER      TO USER SVC_LOADER;
GRANT ROLE TRANSFORMER TO USER SVC_TRANSFORMER;
GRANT ROLE REPORTER    TO USER SVC_REPORTING;

-- Warehouses: USAGE to run queries, OPERATE so a role can resume or suspend its own warehouse.
GRANT USAGE, OPERATE ON WAREHOUSE LOADING      TO ROLE LOADER;
GRANT USAGE, OPERATE ON WAREHOUSE TRANSFORMING TO ROLE TRANSFORMER;
GRANT USAGE, OPERATE ON WAREHOUSE REPORTING    TO ROLE REPORTER;

-- -----------------------------------------------------------------------------------------------------
-- LOADER: owns the raw tables it creates and can create stages, file formats, streams and pipes.
-- -----------------------------------------------------------------------------------------------------
GRANT USAGE ON DATABASE RAW TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE STREAM, CREATE PIPE, CREATE VIEW
    ON SCHEMA RAW.ADMIN_CORE   TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE STREAM, CREATE PIPE, CREATE VIEW
    ON SCHEMA RAW.LEGACY_ADMIN TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT, CREATE STREAM, CREATE PIPE, CREATE VIEW
    ON SCHEMA RAW.NETWORK_FEED TO ROLE LOADER;
GRANT USAGE, CREATE TABLE, CREATE STREAM, CREATE TASK, CREATE VIEW
    ON SCHEMA RAW.AUDIT        TO ROLE LOADER;
-- Tasks in 06 need the account-level EXECUTE TASK privilege (granted by ACCOUNTADMIN):
--   USE ROLE ACCOUNTADMIN; GRANT EXECUTE TASK ON ACCOUNT TO ROLE LOADER;

-- -----------------------------------------------------------------------------------------------------
-- TRANSFORMER: reads all of RAW (current and future objects), builds ANALYTICS.
-- -----------------------------------------------------------------------------------------------------
GRANT USAGE ON DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL TABLES IN DATABASE RAW TO ROLE TRANSFORMER;
GRANT SELECT ON ALL VIEWS IN DATABASE RAW TO ROLE TRANSFORMER;
-- RAW schemas use managed access, so future grants are set per schema (schema-level future grants
-- take precedence over database-level ones).
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.ADMIN_CORE   TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.LEGACY_ADMIN TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.NETWORK_FEED TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA RAW.NETWORK_FEED TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RAW.AUDIT        TO ROLE TRANSFORMER;
-- The pipeline writes reconciliation and diagnostics results to RAW.AUDIT.
GRANT INSERT, UPDATE ON FUTURE TABLES IN SCHEMA RAW.AUDIT TO ROLE TRANSFORMER;
GRANT CREATE TABLE ON SCHEMA RAW.AUDIT TO ROLE TRANSFORMER;

GRANT USAGE, CREATE SCHEMA ON DATABASE ANALYTICS     TO ROLE TRANSFORMER;
GRANT USAGE, CREATE SCHEMA ON DATABASE ANALYTICS_DEV TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.STAGING      TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.INTERMEDIATE TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.SEEDS        TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.SNAPSHOTS    TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.CORE         TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.FINANCE      TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.CLAIMS       TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.DEALER       TO ROLE TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA ANALYTICS.REGULATORY   TO ROLE TRANSFORMER;
-- dbt attaches the row access policies after each rebuild; the APPLY grant is in 04, after the policies exist.
GRANT USAGE ON SCHEMA ANALYTICS.SECURITY TO ROLE TRANSFORMER;

-- -----------------------------------------------------------------------------------------------------
-- REPORTER: marts only. No grant on RAW, STAGING, INTERMEDIATE, SEEDS or SNAPSHOTS.
-- Future grants mean every table dbt (re)creates is readable without a manual grant.
-- -----------------------------------------------------------------------------------------------------
GRANT USAGE ON DATABASE ANALYTICS TO ROLE REPORTER;

GRANT USAGE ON SCHEMA ANALYTICS.CORE       TO ROLE REPORTER;
GRANT USAGE ON SCHEMA ANALYTICS.FINANCE    TO ROLE REPORTER;
GRANT USAGE ON SCHEMA ANALYTICS.CLAIMS     TO ROLE REPORTER;
GRANT USAGE ON SCHEMA ANALYTICS.DEALER     TO ROLE REPORTER;
GRANT USAGE ON SCHEMA ANALYTICS.REGULATORY TO ROLE REPORTER;

GRANT SELECT ON ALL TABLES    IN SCHEMA ANALYTICS.CORE       TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA ANALYTICS.FINANCE    TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA ANALYTICS.CLAIMS     TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA ANALYTICS.DEALER     TO ROLE REPORTER;
GRANT SELECT ON ALL TABLES    IN SCHEMA ANALYTICS.REGULATORY TO ROLE REPORTER;

GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.CORE       TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.FINANCE    TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.CLAIMS     TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.DEALER     TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ANALYTICS.REGULATORY TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ANALYTICS.CORE       TO ROLE REPORTER;

-- Human BI users (for example Power BI over SSO) get REPORTER through a group-mapped role, never a
-- direct grant per person. Each person also needs a row in ANALYTICS.SECURITY.USER_DEALER_ACCESS.
